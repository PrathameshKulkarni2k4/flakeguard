"""Quarantine: set known-flaky tests aside so new flakes stay visible.

A quarantine file is plain text: one glob pattern per line, matched against
a test's key (e.g. ``tests/checkout::test_coupon``). Lines starting with
``#`` are comments. This lets a team say "yes, we know about these" without
hiding genuinely new flakiness.
"""

from __future__ import annotations

import fnmatch
from typing import Iterable, List, Sequence

HEADER = [
    "# flakeguard quarantine",
    "#",
    "# Tests listed here are known-flaky and are set aside so that NEW flakes",
    "# stay visible. One glob pattern per line; '#' starts a comment.",
    "#",
    "# Generated by: flakeguard scan ./reports --update-quarantine",
    "",
]


def load_patterns(path: str) -> List[str]:
    """Read a quarantine file into a list of glob patterns."""
    patterns: List[str] = []
    with open(path, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            patterns.append(line)
    return patterns


def is_quarantined(key: str, patterns: Sequence[str]) -> bool:
    """True if ``key`` matches any quarantine pattern (glob, case-sensitive)."""
    return any(fnmatch.fnmatchcase(key, pattern) for pattern in patterns)


def write_patterns(path: str, keys: Iterable[str]) -> int:
    """Write the given test keys to the quarantine file. Returns the count."""
    unique = sorted(set(keys))
    body = HEADER + unique + [""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(body))
    return len(unique)
