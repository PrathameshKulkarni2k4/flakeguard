"""Quarantine: set known-flaky tests aside so new flakes stay visible.

A quarantine file is plain text: one glob pattern per line, matched against
a test's key (e.g. ``tests/checkout::test_coupon``). Lines starting with
``#`` are comments. This lets a team say "yes, we know about these" without
hiding genuinely new flakiness.

Two things keep it honest:

* Patterns written by flakeguard are **escaped**, so a key like
  ``test_x[1-2]`` (a pytest parametrisation) matches itself rather than
  being read as a character class.
* Entries added by flakeguard are grouped under an ``# added YYYY-MM-DD``
  header, so old ones can be found and reviewed. A quarantined test that
  later breaks for real would otherwise be hidden forever.
"""

from __future__ import annotations

import datetime
import fnmatch
import glob
import os
import re
from typing import Iterable, List, Optional, Sequence

HEADER = [
    "# flakeguard quarantine",
    "#",
    "# Tests listed here are known-flaky and are set aside so that NEW flakes",
    "# stay visible. One glob pattern per line; '#' starts a comment.",
    "#",
    "# Generated by: flakeguard scan ./reports --update-quarantine",
    "",
]

_ADDED_RE = re.compile(r"#\s*added\s+(\d{4}-\d{2}-\d{2})")


def load_patterns(path: str) -> List[str]:
    """Read a quarantine file into a list of glob patterns."""
    patterns: List[str] = []
    with open(path, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            patterns.append(line)
    return patterns


def is_quarantined(key: str, patterns: Sequence[str]) -> bool:
    """True if ``key`` matches any quarantine pattern (glob, case-sensitive)."""
    return any(fnmatch.fnmatchcase(key, pattern) for pattern in patterns)


def update_quarantine(
    path: str, keys: Iterable[str], today: Optional[datetime.date] = None
) -> int:
    """Add ``keys`` to the quarantine file, keeping everything already there.

    Existing patterns and comments are preserved - hand-written globs and
    notes are not clobbered. New entries are grouped under a dated header.
    Returns the number of new patterns added.
    """
    existing_lines: List[str] = []
    existing_patterns: List[str] = []
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            for raw in fh:
                line = raw.rstrip("\n")
                existing_lines.append(line)
                stripped = line.strip()
                if stripped and not stripped.startswith("#"):
                    existing_patterns.append(stripped)

    added: List[str] = []
    known = list(existing_patterns)
    for key in sorted(set(keys)):
        if is_quarantined(key, known + added):
            continue
        # Escape so keys containing [ ] * ? match literally.
        added.append(glob.escape(key))

    if existing_lines:
        lines = list(existing_lines)
        while lines and not lines[-1].strip():
            lines.pop()
        lines.append("")
    else:
        lines = list(HEADER)

    if added:
        date = (today or datetime.date.today()).isoformat()
        lines.append(f"# added {date}")
        lines.extend(added)

    lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return len(added)


def stale_patterns(
    path: str, max_age_days: int, today: Optional[datetime.date] = None
) -> List[str]:
    """Patterns that were added more than ``max_age_days`` ago.

    Hand-written patterns carry no date and are never reported - we cannot
    know when they were added.
    """
    if max_age_days < 0 or not os.path.exists(path):
        return []

    today = today or datetime.date.today()
    cutoff = today - datetime.timedelta(days=max_age_days)

    stale: List[str] = []
    current: Optional[datetime.date] = None
    with open(path, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#"):
                match = _ADDED_RE.match(line)
                current = None
                if match:
                    try:
                        current = datetime.date.fromisoformat(match.group(1))
                    except ValueError:
                        current = None
                continue
            if current is not None and current < cutoff:
                stale.append(line)
    return stale
