"""Regression tests using reports produced by *real* test frameworks.

These fixtures were generated by actually running pytest and jest-junit, so
they capture the real-world quirks (parametrised names, skips, xfail, and
jest's habit of repeating the test name in both classname and name).
"""

import pathlib

from flakeguard.models import Outcome
from flakeguard.parsers.junit_xml import parse_junit_xml

FIXTURES = pathlib.Path(__file__).resolve().parent / "fixtures"


def test_pytest_report_parses_all_cases():
    cases = parse_junit_xml(str(FIXTURES / "pytest-report.xml"))
    assert len(cases) == 9


def test_pytest_outcomes():
    cases = {c.name: c for c in parse_junit_xml(str(FIXTURES / "pytest-report.xml"))}
    assert cases["test_always_passes"].outcome is Outcome.PASSED
    assert cases["test_always_fails"].outcome is Outcome.FAILED
    assert cases["test_skipped"].outcome is Outcome.SKIPPED
    # pytest reports xfail as a skip
    assert cases["test_expected_failure"].outcome is Outcome.SKIPPED


def test_pytest_parametrised_names_are_distinct():
    cases = [c for c in parse_junit_xml(str(FIXTURES / "pytest-report.xml"))
             if c.name.startswith("test_parametrised")]
    assert sorted(c.name for c in cases) == [
        "test_parametrised[1]", "test_parametrised[2]", "test_parametrised[3]"]


def test_pytest_key_is_readable():
    cases = {c.name: c for c in parse_junit_xml(str(FIXTURES / "pytest-report.xml"))}
    assert cases["test_always_fails"].key == "pytest::sample_tests::test_always_fails"


def test_jest_report_parses_all_cases():
    cases = parse_junit_xml(str(FIXTURES / "jest-report.xml"))
    assert len(cases) == 4


def test_jest_key_does_not_repeat_the_name():
    # jest-junit sets classname == name; the key must not duplicate it.
    cases = {c.name: c for c in parse_junit_xml(str(FIXTURES / "jest-report.xml"))}
    key = cases["math adds two numbers"].key
    assert key == "math::math adds two numbers"
    assert key.count("math adds two numbers") == 1


def test_jest_failure_detected():
    cases = {c.name: c for c in parse_junit_xml(str(FIXTURES / "jest-report.xml"))}
    assert cases["math a failing one"].outcome is Outcome.FAILED
    assert cases["math a skipped one"].outcome is Outcome.SKIPPED
